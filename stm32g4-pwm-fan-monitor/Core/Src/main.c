{
    if(GPIO_Pin == B1_Pin) // Tetiklenen pin mavi buton ise
    {
        // Gecikme kullanmadan doğrudan durum makinesini turlatıyoruz
        if(guncel_duty == 25) {
            guncel_duty = 50;
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 480);
        }
        else if(guncel_duty == 50) {
            guncel_duty = 75;
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 720);
        }
        else if(guncel_duty == 75) {
            guncel_duty = 100;
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 959);
        }
        else {
            guncel_duty = 25;
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 240);
        }
    }
}





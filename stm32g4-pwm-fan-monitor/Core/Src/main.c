void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM3) // TIM3 Kesmesi
    {
        if (htim->Channel == HAL_TIM_ACTIVE_CHANNEL_2) // TIM3 Channel 2 (PA4)
        {
            if (ilk_kenar == 0)
            {
                ilk_yakalama = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_2);
                ilk_kenar = 1;
            }
            else
            {
                ikinci_yakalama = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_2);

                if (ikinci_yakalama > ilk_yakalama)
                {
                    fark = ikinci_yakalama - ilk_yakalama;
                }
                else
                {
                    fark = (65535 - ilk_yakalama) + ikinci_yakalama; // Taşma koruması
                }

                if (fark > 0)
                {
                    // Giriş Yakalama frekansımız 1 MHz (PSC=169 ayarı ile)
                    // İki düşen kenar arası mikrosaniye cinsinden süre = fark

                    // 1. Tacho Sinyal Frekansı Hesabı (Hz)
                    fan_freq = 1000000 / fark;

                    // 2. RPM calculation (assumes 2 tach pulses per revolution)
                    fan_rpm = (fan_freq * 60) / 2;
                }

                ilk_kenar = 0; // Süreci sıfırla
            }
        }
    }
}

